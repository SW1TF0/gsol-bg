-- Публичен каталог
create policy "Активните категории са публични" on public.categories
  for select to anon, authenticated using (is_active or (select public.is_staff()));
create policy "Активните продукти са публични" on public.products
  for select to anon, authenticated using (is_active or (select public.is_staff()));

-- Служителите управляват каталога (без ролите техник)
create policy "Служители редактират категории" on public.categories
  for all to authenticated
  using ((select public.is_staff(array['admin', 'manager', 'editor']::public.staff_role[])))
  with check ((select public.is_staff(array['admin', 'manager', 'editor']::public.staff_role[])));
create policy "Служители редактират продукти" on public.products
  for all to authenticated
  using ((select public.is_staff(array['admin', 'manager', 'editor']::public.staff_role[])))
  with check ((select public.is_staff(array['admin', 'manager', 'editor']::public.staff_role[])));

-- Поръчки, клиенти и история — всички служители четат; продажби и мениджъри променят
create policy "Служители четат поръчки" on public.orders
  for select to authenticated using ((select public.is_staff()));
create policy "Продажби обновяват поръчки" on public.orders
  for update to authenticated
  using ((select public.is_staff(array['admin', 'manager', 'sales']::public.staff_role[])))
  with check ((select public.is_staff(array['admin', 'manager', 'sales']::public.staff_role[])));
create policy "Служители четат артикули" on public.order_items
  for select to authenticated using ((select public.is_staff()));
create policy "Служители четат история" on public.order_events
  for select to authenticated using ((select public.is_staff()));
create policy "Служители добавят бележки" on public.order_events
  for insert to authenticated with check ((select public.is_staff()) and actor = (select auth.uid()));
create policy "Служители четат клиенти" on public.customers
  for select to authenticated using ((select public.is_staff()));

-- Промо кодове — мениджъри и администратори
create policy "Мениджъри управляват промо кодове" on public.promo_codes
  for all to authenticated
  using ((select public.is_staff(array['admin', 'manager']::public.staff_role[])))
  with check ((select public.is_staff(array['admin', 'manager']::public.staff_role[])));
create policy "Служители четат използванията" on public.promo_redemptions
  for select to authenticated using ((select public.is_staff()));

-- Настройки и служители — само администратори пишат
create policy "Служители четат настройките" on public.settings
  for select to authenticated using ((select public.is_staff()));
create policy "Админи пишат настройките" on public.settings
  for all to authenticated
  using ((select public.is_staff(array['admin']::public.staff_role[])))
  with check ((select public.is_staff(array['admin']::public.staff_role[])));
create policy "Служителят вижда себе си, админът — всички" on public.staff
  for select to authenticated
  using (user_id = (select auth.uid()) or (select public.is_staff(array['admin']::public.staff_role[])));
create policy "Админи управляват служителите" on public.staff
  for all to authenticated
  using ((select public.is_staff(array['admin']::public.staff_role[])))
  with check ((select public.is_staff(array['admin']::public.staff_role[])));
