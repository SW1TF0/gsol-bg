-- ---------------------------------------------------------------- служители и роли
create type public.staff_role as enum ('admin', 'manager', 'sales', 'technician', 'editor');

create table public.staff (
  user_id uuid primary key references auth.users on delete cascade,
  role public.staff_role not null default 'sales',
  display_name text,
  created_at timestamptz not null default now()
);

-- true, ако текущият потребител е служител (по избор: с една от изброените роли)
create function public.is_staff(roles public.staff_role[] default null)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.staff s
    where s.user_id = (select auth.uid())
      and (roles is null or s.role = any (roles))
  );
$$;

