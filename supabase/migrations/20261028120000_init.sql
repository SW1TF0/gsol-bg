-- ---------------------------------------------------------------- промо кодове
create type public.discount_type as enum ('percent', 'fixed', 'free_shipping');

create table public.promo_codes (
  id bigint generated always as identity primary key,
  code text not null unique check (code = upper(code) and code ~ '^[A-Z0-9_-]{3,32}$'),
  description text,
  discount_type public.discount_type not null,
  percent numeric(5, 2) check (percent is null or (percent > 0 and percent <= 100)),
  amount_cents int check (amount_cents is null or amount_cents > 0),
  -- обхват: цялата поръчка или само избрани категории / марки / продукти
  scope text not null default 'order' check (scope in ('order', 'categories', 'brands', 'products')),
  scope_category_ids bigint[] not null default '{}',
  scope_brands text[] not null default '{}',
  scope_product_ids bigint[] not null default '{}',
  exclude_promo_items boolean not null default false,
  min_subtotal_cents int not null default 0,
  max_discount_cents int,
  starts_at timestamptz,
  ends_at timestamptz,
  usage_limit int check (usage_limit is null or usage_limit > 0),
  per_customer_limit int check (per_customer_limit is null or per_customer_limit > 0),
  first_order_only boolean not null default false,
  allowed_emails text[] not null default '{}',
  batch_id uuid,
  partner text,
  is_active boolean not null default true,
  times_used int not null default 0,
  created_by uuid references auth.users on delete set null,
  created_at timestamptz not null default now(),
  constraint promo_value_matches_type check (
    (discount_type = 'percent' and percent is not null)
    or (discount_type = 'fixed' and amount_cents is not null)
    or discount_type = 'free_shipping'
  )
);
create index promo_codes_batch_idx on public.promo_codes (batch_id) where batch_id is not null;

-- ---------------------------------------------------------------- поръчки
create type public.order_status as enum ('new', 'confirmed', 'processing', 'shipped', 'delivered', 'cancelled', 'returned');

create sequence public.order_number_seq start 100001;

create table public.orders (
  id bigint generated always as identity primary key,
  number text not null unique default ('GS-' || nextval('public.order_number_seq')),
  customer_id uuid references public.customers on delete set null,
  status public.order_status not null default 'new',
  email text not null,
  phone text not null,
  first_name text not null,
  last_name text not null,
  shipping_method text not null check (shipping_method in ('econt_office', 'econt_address')),
  shipping_city text not null,
  shipping_address text,
  econt_office text,
  payment_method text not null check (payment_method in ('cod', 'bank')),
  invoice jsonb,
  note text,
  subtotal_cents int not null,
  discount_cents int not null default 0,
  shipping_cents int not null default 0,
  total_cents int not null,
  promo_code_id bigint references public.promo_codes on delete set null,
  promo_code text,
  utm jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index orders_status_idx on public.orders (status, created_at desc);
create index orders_email_idx on public.orders (lower(email));

create table public.order_items (
  id bigint generated always as identity primary key,
  order_id bigint not null references public.orders on delete cascade,
  product_id bigint references public.products on delete set null,
  name text not null,
  sku text,
  unit_price_cents int not null,
  qty int not null check (qty > 0),
  discount_cents int not null default 0,
  line_total_cents int not null
);
create index order_items_order_idx on public.order_items (order_id);

-- история и бележки по поръчката
create table public.order_events (
  id bigint generated always as identity primary key,
  order_id bigint not null references public.orders on delete cascade,
  actor uuid references auth.users on delete set null,
  type text not null,
  data jsonb not null default '{}',
  created_at timestamptz not null default now()
