create index order_events_order_idx on public.order_events (order_id, created_at);

create table public.promo_redemptions (
  id bigint generated always as identity primary key,
  promo_code_id bigint not null references public.promo_codes on delete cascade,
  order_id bigint not null references public.orders on delete cascade,
  email text not null,
  discount_cents int not null,
  created_at timestamptz not null default now()
);
create index promo_redemptions_code_idx on public.promo_redemptions (promo_code_id, lower(email));

-- ---------------------------------------------------------------- updated_at
create function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger products_touch before update on public.products
  for each row execute function public.touch_updated_at();
create trigger orders_touch before update on public.orders
  for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------- създаване на поръчка
-- Сървърът изчислява цените и отстъпката (src/lib/promo.ts) и вика тази функция.
-- Тя в една транзакция заключва промо кода, проверява лимитите отново и записва всичко.
create function public.create_order(p_order jsonb, p_items jsonb)
returns table (order_id bigint, order_number text)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_promo public.promo_codes;
  v_email text := lower(p_order ->> 'email');
  v_customer uuid;
  v_order public.orders;
  v_used_by_customer int;
begin
  if p_order ->> 'promo_code_id' is not null then
    select * into v_promo from public.promo_codes
      where id = (p_order ->> 'promo_code_id')::bigint
      for update;
    if not found or not v_promo.is_active then
      raise exception 'PROMO_INVALID';
    end if;
    if v_promo.usage_limit is not null and v_promo.times_used >= v_promo.usage_limit then
      raise exception 'PROMO_EXHAUSTED';
    end if;
    if v_promo.per_customer_limit is not null then
      select count(*) into v_used_by_customer from public.promo_redemptions
        where promo_code_id = v_promo.id and lower(email) = v_email;
      if v_used_by_customer >= v_promo.per_customer_limit then
        raise exception 'PROMO_CUSTOMER_LIMIT';
      end if;
    end if;
  end if;

  insert into public.customers (email, phone, first_name, last_name, company, marketing_opt_in)
  values (
    v_email,
    p_order ->> 'phone',
    p_order ->> 'first_name',
    p_order ->> 'last_name',
    p_order -> 'invoice',
    coalesce((p_order ->> 'marketing_opt_in')::boolean, false)
  )
  on conflict (lower(email)) do update set
    phone = excluded.phone,
    first_name = excluded.first_name,
    last_name = excluded.last_name,
    company = coalesce(excluded.company, public.customers.company),
    marketing_opt_in = public.customers.marketing_opt_in or excluded.marketing_opt_in
  returning id into v_customer;

  insert into public.orders (
    customer_id, email, phone, first_name, last_name,
    shipping_method, shipping_city, shipping_address, econt_office,
    payment_method, invoice, note,
    subtotal_cents, discount_cents, shipping_cents, total_cents,
    promo_code_id, promo_code, utm
  ) values (
    v_customer, v_email, p_order ->> 'phone', p_order ->> 'first_name', p_order ->> 'last_name',
    p_order ->> 'shipping_method', p_order ->> 'shipping_city', p_order ->> 'shipping_address', p_order ->> 'econt_office',
    p_order ->> 'payment_method', p_order -> 'invoice', p_order ->> 'note',
    (p_order ->> 'subtotal_cents')::int, (p_order ->> 'discount_cents')::int,
    (p_order ->> 'shipping_cents')::int, (p_order ->> 'total_cents')::int,
    v_promo.id, v_promo.code, p_order -> 'utm'
  ) returning * into v_order;

  insert into public.order_items (order_id, product_id, name, sku, unit_price_cents, qty, discount_cents, line_total_cents)
  select v_order.id, (i ->> 'product_id')::bigint, i ->> 'name', i ->> 'sku',
         (i ->> 'unit_price_cents')::int, (i ->> 'qty')::int,
         (i ->> 'discount_cents')::int, (i ->> 'line_total_cents')::int
  from jsonb_array_elements(p_items) as i;

  insert into public.order_events (order_id, type, data)
  values (v_order.id, 'created', jsonb_build_object('total_cents', v_order.total_cents));

  if v_promo.id is not null then
    insert into public.promo_redemptions (promo_code_id, order_id, email, discount_cents)
    values (v_promo.id, v_order.id, v_email, v_order.discount_cents);
    update public.promo_codes set times_used = times_used + 1 where id = v_promo.id;
  end if;

  return query select v_order.id, v_order.number;
end;
$$;

-- Само сървърът (service role) може да създава поръчки
revoke execute on function public.create_order(jsonb, jsonb) from public, anon, authenticated;

